/*
Проблема: 1910 Руины титанов: сокрытый вход

Ввод
В первой строке дано единственное целое число n —
количество секций стены (3 ≤ n ≤ 1000).
Во второй строке через пробел записаны n положительных целых чисел ai —
сила магического поля на каждой из секций (1 ≤ ai ≤ 106).

Вывод
Выдайте через пробел два числа — максимальную суммарную силу поля возле
трёх подряд идущих секций стены и номер средней из них.
Гарантируется, что ответ всегда однозначен.

исходные данные
6
1 4 4 4 1 1

результат
12 3
*/

import java.util.Scanner;

public class task1910 {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);

        int n = sc.nextInt();

        int[] a = new int[n];

        // Считываем силы магического поля
        for (int i = 0; i < n; i++) {
            a[i] = sc.nextInt();
        }

        // Сумма первых трех секций
        int sum = a[0] + a[1] + a[2];

        int maxSum = sum;

        // Номер средней секции (нумерация с 1)
        int middle = 2;

        // Перебираем все три подряд идущие секции
        for (int i = 1; i <= n - 3; i++) {

            // Обновляем сумму за O(1)
            sum = sum - a[i - 1] + a[i + 2];

            // Если нашли большую сумму
            if (sum > maxSum) {
                maxSum = sum;
                middle = i + 2;
            }
        }

        // Выводим максимальную сумму и номер средней секции
        System.out.println(maxSum + " " + middle);

        sc.close();
    }
}
